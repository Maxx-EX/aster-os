// Aster Kernel — 构建脚本：把 C 侧支持代码编译成静态库再交给 rustc 链接
use std::env;
use std::path::PathBuf;
use std::process::Command;

fn main() {
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let c_dir = manifest.join("c");

    let cc = env::var("ASTER_CC").unwrap_or_else(|_| "aarch64-linux-gnu-gcc".to_string());
    let flags = [
        "-c", "-O2", "-ffreestanding", "-fno-builtin",
        "-fno-stack-protector", "-nostdlib",
        "-mgeneral-regs-only", "-DARMTARGET",
    ];

    let sources = ["aster_c.c", "sha256.c"];
    let mut objs = Vec::new();
    for src in sources {
        let obj = out.join(src.replace(".c", ".o"));
        let status = Command::new(&cc)
            .args(&flags)
            .arg(c_dir.join(src))
            .arg("-o")
            .arg(&obj)
            .status()
            .expect("调用交叉编译器失败");
        if !status.success() {
            panic!("编译 {} 失败", src);
        }
        objs.push(obj);
    }

    let ar = env::var("ASTER_AR").unwrap_or_else(|_| "aarch64-linux-gnu-ar".to_string());
    let lib = out.join("libaster_c.a");
    let _ = std::fs::remove_file(&lib);
    let status = Command::new(&ar)
        .arg("rcs")
        .arg(&lib)
        .args(&objs)
        .status()
        .expect("调用交叉 ar 失败");
    if !status.success() {
        panic!("打包 libaster_c.a 失败");
    }

    println!("cargo:rustc-link-search=native={}", out.display());
    println!("cargo:rustc-link-lib=static=aster_c");
    println!("cargo:rerun-if-changed=c");

    // 把用户程序（扁平二进制）编成 Rust 静态数组嵌进内核：
    // 内核启动后用 mmu::load_user_image 把它拷进用户代码页，再切 EL0 执行。
    let mut src = String::from("// generated by kernel/build.rs\n");
    for (env_key, static_name, default) in [
        ("ASTER_USER_BIN",       "USER_HELLO", "../build/user/hello.bin"),
        ("ASTER_USER_FAULT_BIN", "USER_FAULT", "../build/user/fault.bin"),
        ("ASTER_USER_BUSY_BIN",  "USER_BUSY",  "../build/user/busy.bin"),
        ("ASTER_USER_ISO_BIN",   "USER_ISO",   "../build/user/iso.bin"),
        ("ASTER_USER_FP_BIN",    "USER_FP",    "../build/user/fp.bin"),
        ("ASTER_USER_WX_BIN",    "USER_WX",    "../build/user/wx.bin"),
        ("ASTER_USER_YIELD_BIN", "USER_YIELD", "../build/user/yield.bin"),
        ("ASTER_USER_FILE_BIN",  "USER_FILE",  "../build/user/file.bin"),
    ] {
        let path = env::var(env_key).map(PathBuf::from).unwrap_or_else(|_| manifest.join(default));
        let size_name = format!("{}_SIZE", static_name);
        if path.exists() {
            let bytes = std::fs::read(&path).expect("读用户程序失败");
            src.push_str(&format!("pub static {}: &[u8] = &[", static_name));
            for (i, b) in bytes.iter().enumerate() {
                if i % 16 == 0 {
                    src.push('\n');
                }
                src.push_str(&format!("0x{:02x},", b));
            }
            src.push_str("];\n");
            src.push_str(&format!("pub const {}: usize = {};\n", size_name, bytes.len()));
            println!("cargo:warning=内嵌 {} {} bytes", static_name, bytes.len());
        } else {
            src.push_str(&format!("pub static {}: &[u8] = &[];\n", static_name));
            src.push_str(&format!("pub const {}: usize = 0;\n", size_name));
            println!("cargo:warning=没找到 {}，对应命令不可用（先 make user）", path.display());
        }
        println!("cargo:rerun-if-changed={}", path.display());
    }
    std::fs::write(out.join("user_image.rs"), src).expect("写 user_image.rs 失败");
}
